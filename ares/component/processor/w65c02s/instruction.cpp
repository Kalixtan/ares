#define op(id, name, ...) case id: return instruction##name(__VA_ARGS__);
#define fp(name) &WDC65C02S::algorithm##name
#define addr(name) &WDC65C02S::address##name

auto WDC65C02S::interrupt() -> void {
  idle();
  idle();
  push(PCH);
  push(PCL);
  n16 vector = 0xfffe;
  nmi(vector);
  push(P | 0x20);
  I = 1;
  //65C02 hardware clears D on interrupt entry, same reasoning as algorithmBRK.
  D = 0;
  PCL = read(vector++);
L PCH = read(vector++);
}

auto WDC65C02S::reset() -> void {
  waiting = 0;
  stopped = 0;
  idle();
  idle();
  read(0x0100 | S--); // Dummy push (PCH)
  read(0x0100 | S--); // Dummy push (PCL)
  n16 vector = 0xfffc;
  read(0x0100 | S--); // Dummy push (P)
  I = 1;
  PCL = read(vector++);
L PCH = read(vector++);
}

